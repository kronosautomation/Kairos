<#
.SYNOPSIS
  Writes the SLSA build provenance (v1) predicate of a release: what was built, from which commit, by which pipeline run, with which toolchain.

.DESCRIPTION
  The predicate is attached to every artifact by Attest-Packages.ps1 (and to each container image), where cosign wraps it in an in-toto statement whose subject is the artifact's SHA-256 and signs it
  with the release key. Values come from the Azure Pipelines run (the standard predefined variables); outside a pipeline they say so ("local"), which a verifier is meant to reject.

  What this claims, and what it does not: the provenance is generated by the release pipeline's own steps and signed with a key that only that pipeline's identity can use. That is SLSA Build level 2
  (a hosted build service produced signed provenance). It is not level 3: the signing step runs in the same job as the build, so a compromised build step could in principle ask for a signature.
  docs/RELEASE.md says so too.

.PARAMETER Version     The release version.
.PARAMETER Output      The predicate file to write.
.PARAMETER Sources     Repositories built: array of @{ Name; Uri; Commit; Ref }. Default: the one at -Root, read from git.
.PARAMETER Byproducts  Files that came out of the build but are not what is released (SBOMs, the reproducibility report): their digests are recorded.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Version,
    [Parameter(Mandatory)][string]$Output,
    [string]$Root = '',
    [hashtable[]]$Sources = @(),
    [string[]]$Byproducts = @(),
    [string]$Pipeline = 'build/azure-pipelines-release.yml'
)

. (Join-Path $PSScriptRoot 'common.ps1')
if (-not $Root) { $Root = Get-RepoRoot }

function Get-Env([string]$name, [string]$fallback = 'local') {
    $value = [Environment]::GetEnvironmentVariable($name)
    if ([string]::IsNullOrEmpty($value)) { $fallback } else { $value }
}

if ($Sources.Count -eq 0) {
    $Sources = @(@{
        Name   = Split-Path -Leaf $Root
        Uri    = (Get-Env 'BUILD_REPOSITORY_URI' ((& git -C $Root config --get remote.origin.url) ?? 'local'))
        Commit = (& git -C $Root rev-parse HEAD).Trim()
        Ref    = (Get-Env 'BUILD_SOURCEBRANCH' ((& git -C $Root rev-parse --abbrev-ref HEAD).Trim()))
    })
}

$collection = (Get-Env 'SYSTEM_COLLECTIONURI' 'local').TrimEnd('/')
$project = Get-Env 'SYSTEM_TEAMPROJECT'
$definition = Get-Env 'SYSTEM_DEFINITIONID' '0'
$buildId = Get-Env 'BUILD_BUILDID' '0'
$inPipeline = [bool]$env:TF_BUILD

$tools = Get-Content -LiteralPath (Join-Path $Root '.config/dotnet-tools.json') -Raw | ConvertFrom-Json
$toolVersions = [ordered]@{ dotnet = (& dotnet --version).Trim() }
foreach ($tool in $tools.tools.PSObject.Properties) { $toolVersions[$tool.Name] = $tool.Value.version }
$installer = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'Install-ReleaseTools.ps1') -Raw
foreach ($name in 'cosign', 'syft') { if ($installer -match "(?s)$name\s*=\s*@\{\s*Version\s*=\s*'([^']+)'") { $toolVersions[$name] = $Matches[1] } }

# Lists, not @(...): PowerShell unrolls a single ordered dictionary inside @(), and the JSON then holds its type name instead of the object.
$resolved = [System.Collections.Generic.List[object]]::new()
foreach ($source in $Sources) {
    $resolved.Add([ordered]@{ name = $source.Name; uri = "git+$($source.Uri)@$($source.Ref)"; digest = [ordered]@{ gitCommit = $source.Commit } })
}
$recorded = [System.Collections.Generic.List[object]]::new() # (not $byproducts: PowerShell names are case-insensitive, and that is the typed parameter)
foreach ($file in $Byproducts) {
    if (Test-Path -LiteralPath $file) { $recorded.Add([ordered]@{ name = (Split-Path -Leaf $file); digest = [ordered]@{ sha256 = (Get-Sha256 $file) } }) }
}

$predicate = [ordered]@{
    buildDefinition = [ordered]@{
        buildType            = 'urn:kronos-automation:kairos:release:azure-pipelines:v1'
        externalParameters   = [ordered]@{ pipeline = $Pipeline; version = $Version; ref = ($Sources[0]).Ref }
        internalParameters   = [ordered]@{ continuousIntegrationBuild = $true; lockedRestore = $true; tools = $toolVersions; agentOs = (Get-Env 'AGENT_OS' ([Runtime.InteropServices.RuntimeInformation]::OSDescription)); agentArchitecture = (Get-Env 'AGENT_OSARCHITECTURE' ([Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString())) }
        resolvedDependencies = $resolved
    }
    runDetails      = [ordered]@{
        builder  = [ordered]@{ id = "$collection/$project/_build?definitionId=$definition"; version = $toolVersions }
        metadata = [ordered]@{ invocationId = "$collection/$project/_build/results?buildId=$buildId"; startedOn = (Get-Env 'KAIROS_BUILD_STARTED' ([DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ'))) ; finishedOn = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ') }
        byproducts = $recorded
    }
}
if (-not $inPipeline) { $predicate.runDetails.builder.id = 'local'; $predicate.runDetails.metadata.invocationId = 'local' }

New-Item -ItemType Directory -Force -Path (Split-Path -Parent ([IO.Path]::GetFullPath($Output))) | Out-Null
$predicate | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath $Output -Encoding utf8NoBOM
Write-Host "Wrote the provenance predicate: $Output ($(if ($inPipeline) { "pipeline run $buildId" } else { 'local run, not a release' }))"
